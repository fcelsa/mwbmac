// Ponte fra gli appunti del Mac (NSPasteboard) e quelli di Mouse Without Borders.
//
// Mac → PC: NSPasteboard non notifica i cambiamenti, quindi si controlla `changeCount`
// due volte al secondo. Come su Windows, se c'è del testo vince il testo, altrimenti
// l'immagine; i file copiati nel Finder restano fuori.
// PC → Mac: i dati ricevuti vengono verificati e scritti negli appunti; il contatore
// risultante viene ricordato per non rispedirli indietro.
// Le conversioni pesanti (compressione, ricodifica delle immagini) girano fuori dal
// thread principale; l'accesso a NSPasteboard resta sul thread principale.

import AppKit
import Foundation
import ImageIO
import MWBProtocol
import MWBTransport
import UniformTypeIdentifiers

public final class ClipboardBridge: NSObject, NSPasteboardItemDataProvider {
    private let session: Session
    private let log: Log
    /// Macchina sotto controllo in questo momento (thread principale), se c'è.
    private let activeMachine: () -> UInt32?
    private let pasteboard = NSPasteboard.general
    private let worker = DispatchQueue(label: "mwbmac.clipboard", qos: .userInitiated)

    private var timer: Timer?
    private var lastChangeCount = 0
    /// Contatore degli appunti dopo una nostra scrittura: quel cambiamento non va inviato.
    private var ownChangeCount = -1
    private var lastSentDigest: Int?
    /// Serve a scartare una lettura superata da una copia più recente.
    private var generation = 0
    /// PNG da cui produrre il TIFF su richiesta (vedi `pasteboard(_:item:provideDataForType:)`).
    private var promisedImage: Data?

    /// Tipi con cui i gestori di password segnalano contenuti da non propagare.
    private static let confidentialTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]
    /// Oltre questa dimensione il testo non viene inviato (prima della compressione).
    private static let maxTextBytes = 64 * 1024 * 1024
    /// 64 milioni di pixel (8K è 33 milioni): oltre, la sola bitmap supera i 256 MB.
    private static let maxPixels = 64_000_000

    public init(session: Session, log: Log, activeMachine: @escaping () -> UInt32?) {
        self.session = session
        self.log = log
        self.activeMachine = activeMachine
    }

    /// Da chiamare sul thread principale.
    public func start() {
        // Ciò che è già negli appunti all'avvio non viene inviato.
        lastChangeCount = pasteboard.changeCount
        session.onClipboardReceived = { [weak self] payload, machine in
            self?.worker.async { self?.received(payload, from: machine) }
        }
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    public func stop() {
        timer?.invalidate()
        timer = nil
        session.onClipboardReceived = nil
    }

    // MARK: Mac → PC

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard count != ownChangeCount else { return }
        generation += 1
        readPasteboard(generation: generation, attempt: 0)
    }

    private func readPasteboard(generation: Int, attempt: Int) {
        guard generation == self.generation else { return }
        let types = pasteboard.types ?? []
        let rawTypes = Set(types.map(\.rawValue))
        guard rawTypes.isDisjoint(with: ClipboardBridge.confidentialTypes) else {
            log.debug("Concealed clipboard (password manager): not sent")
            return
        }
        guard !types.contains(.fileURL) else {
            log.debug("Clipboard with files: not sent (file transfer not supported)")
            return
        }

        if let plain = pasteboard.string(forType: .string), !plain.isEmpty {
            guard plain.utf16.count * 2 <= ClipboardBridge.maxTextBytes else {
                log.info("Clipboard text too large, not sent")
                return
            }
            let rtf = pasteboard.data(forType: .rtf).flatMap { String(data: $0, encoding: .utf8) ?? String(data: $0, encoding: .windowsCP1252) }
            let html = pasteboard.string(forType: .html)
            worker.async { [weak self] in
                let text = ClipboardText(plain: ClipboardText.windowsLineEndings(plain), rtf: rtf,
                                         html: html.map(CFHTML.wrap))
                self?.publish(ClipboardPayload(kind: .text, data: text.encoded()), generation: generation,
                              description: "text, \(plain.count) characters")
            }
            return
        }

        let imageTypes: [NSPasteboard.PasteboardType] = [.png, .tiff, NSPasteboard.PasteboardType("public.jpeg"),
                                                         NSPasteboard.PasteboardType("public.heic"), .pdf]
        if let type = imageTypes.first(where: types.contains) {
            guard let data = pasteboard.data(forType: type), !data.isEmpty else {
                // Alcune applicazioni forniscono i dati in ritardo: si riprova una volta.
                if attempt < 2 {
                    DispatchQueue.main.asyncAfter(deadline: .now() + 0.2) { [weak self] in
                        self?.readPasteboard(generation: generation, attempt: attempt + 1)
                    }
                }
                return
            }
            worker.async { [weak self] in
                guard let self else { return }
                guard let png = ClipboardBridge.normalizedPNG(from: data) else {
                    self.log.info("Clipboard image unreadable (\(type.rawValue)), not sent")
                    return
                }
                self.publish(ClipboardPayload(kind: .image, data: [UInt8](png)), generation: generation,
                             description: "image, \(png.count / 1024) KB")
            }
        }
    }

    /// Fuori dal thread principale.
    private func publish(_ payload: ClipboardPayload, generation: Int, description: String) {
        guard !payload.data.isEmpty else { return }
        var hasher = Hasher()
        hasher.combine(payload.kind)
        hasher.combine(payload.data)
        let digest = hasher.finalize()
        DispatchQueue.main.async { [self] in
            // Una copia più recente ha superato questa; contenuto identico all'ultimo inviato.
            guard generation == self.generation, digest != lastSentDigest else { return }
            lastSentDigest = digest
            log.info("Clipboard → PC: \(description)")
            session.sendClipboard(payload, activeMachine: activeMachine())
        }
    }

    // MARK: PC → Mac

    /// Fuori dal thread principale: decodifica e verifica, poi scrive sul thread principale.
    private func received(_ payload: ClipboardPayload, from machine: Session.Machine) {
        switch payload.kind {
        case .text:
            guard let text = try? ClipboardText(decoding: payload.data) else {
                log.info("Text received from \(machine.name) cannot be decoded, ignored")
                return
            }
            let plain = text.plain.map(ClipboardText.macLineEndings)
            let html = text.html.map(CFHTML.unwrap)
            DispatchQueue.main.async { [self] in
                let item = NSPasteboardItem()
                if let plain { item.setString(plain, forType: .string) }
                if let rtf = text.rtf, let data = rtf.data(using: .utf8) { item.setData(data, forType: .rtf) }
                if let html { item.setString(html, forType: .html) }
                guard !item.types.isEmpty else { return }
                write([item])
                log.info("Clipboard ← \(machine.name): text, \((plain ?? html ?? "").count) characters")
            }
        case .image:
            // PowerToys invia sempre PNG (con zeri in coda). Dalla rete si accetta solo quello:
            // niente PDF, TIFF o altri formati, i cui decodificatori sarebbero superficie
            // d'attacco inutile.
            guard let sanitized = PNGData.sanitized(payload.data),
                  let png = ClipboardBridge.normalizedPNG(from: Data(sanitized), convertToSRGB: false,
                                                          allowVectorFallback: false) else {
                log.info("Image received from \(machine.name) cannot be decoded (\(payload.data.count) bytes), ignored")
                return
            }
            DispatchQueue.main.async { [self] in
                let item = NSPasteboardItem()
                item.setData(png, forType: .png)
                // Molte applicazioni Mac incollano solo TIFF: lo si produce su richiesta,
                // senza tenere negli appunti decine di megabyte non compressi.
                promisedImage = png
                item.setDataProvider(self, forTypes: [.tiff])
                write([item])
                log.info("Clipboard ← \(machine.name): image, \(png.count / 1024) KB")
            }
        }
    }

    private func write(_ items: [NSPasteboardItem]) {
        pasteboard.clearContents()
        pasteboard.writeObjects(items)
        ownChangeCount = pasteboard.changeCount
        lastChangeCount = ownChangeCount
        // Ciò che arriva dal PC non è "l'ultimo inviato": una successiva copia identica sul Mac va inviata.
        lastSentDigest = nil
    }

    /// Gli appunti sono passati ad altro contenuto: il PNG promesso non serve più.
    public func pasteboardFinishedWithDataProvider(_ pasteboard: NSPasteboard) {
        DispatchQueue.main.async { [weak self] in self?.promisedImage = nil }
    }

    public func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        guard type == .tiff, let png = promisedImage, let rep = NSBitmapImageRep(data: png),
              let tiff = rep.representation(using: .tiff, properties: [.compressionMethod: NSBitmapImageRep.TIFFCompression.lzw]) else { return }
        item.setData(tiff, forType: .tiff)
    }

    // MARK: Immagini

    /// Decodifica un'immagine in qualunque formato noto al sistema e la ricodifica in PNG
    /// a 8 bit per canale. Verso il PC si converte in sRGB: gli schermi dei Mac catturano
    /// in Display P3 e molte applicazioni Windows ignorano il profilo colore.
    /// Restituisce `nil` se i dati non sono un'immagine valida.
    static func normalizedPNG(from data: Data, convertToSRGB: Bool = true, allowVectorFallback: Bool = true) -> Data? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              CGImageSourceGetCount(source) > 0,
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else {
            // PDF e formati vettoriali (solo dagli appunti del Mac): li rasterizza AppKit,
            // con lo stesso limite di pixel delle immagini.
            guard allowVectorFallback, let vector = NSImage(data: data) else { return nil }
            let size = vector.size
            guard size.width > 0, size.height > 0, size.width * size.height * 4 <= Double(maxPixels) else { return nil }
            guard let rep = vector.tiffRepresentation.flatMap(NSBitmapImageRep.init(data:)) else { return nil }
            return rep.representation(using: .png, properties: [:])
        }
        let width = image.width
        let height = image.height
        guard width > 0, height > 0, width * height <= maxPixels else { return nil }

        var output = image
        let needsConversion = image.bitsPerComponent != 8
            || (convertToSRGB && image.colorSpace?.name != CGColorSpace.sRGB)
        if needsConversion, let space = CGColorSpace(name: CGColorSpace.sRGB),
           let context = CGContext(data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: 0,
                                   space: space, bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue) {
            context.draw(image, in: CGRect(x: 0, y: 0, width: width, height: height))
            if let converted = context.makeImage() { output = converted }
        }

        let encoded = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(encoded, UTType.png.identifier as CFString, 1, nil) else {
            return nil
        }
        CGImageDestinationAddImage(destination, output, nil)
        guard CGImageDestinationFinalize(destination), encoded.length > 0 else { return nil }
        return encoded as Data
    }
}
